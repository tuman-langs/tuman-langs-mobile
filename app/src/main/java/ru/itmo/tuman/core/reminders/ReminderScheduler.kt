package ru.itmo.tuman.core.reminders

import java.time.LocalTime

/**
 * Ежедневное напоминание (ФТ-11). Для экрана настроек (#35): он вызывает только эти методы,
 * а они сами сохраняют выбор в настройках и (пере)планируют уведомление.
 */
interface ReminderScheduler {

    /** Включить напоминание на [time] или перенести его на новое время. */
    suspend fun enable(time: LocalTime)

    /** Выключить напоминание. Выбранное время запоминается — при включении оно снова предложится. */
    suspend fun disable()

    /**
     * Привести расписание в соответствие с настройками. Вызывается при запуске приложения:
     * если напоминание включено, а запланированной работы нет (например, после переустановки),
     * она появится; уже запланированную не трогает.
     */
    suspend fun sync()

    /**
     * Можно ли показывать уведомления. На Android 13+ нужно разрешение POST_NOTIFICATIONS,
     * а на любой версии пользователь может выключить уведомления в настройках телефона.
     * `false` — экран показывает плашку «Уведомления запрещены» (#35).
     */
    fun hasPermission(): Boolean
}
