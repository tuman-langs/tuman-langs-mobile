package ru.itmo.tuman.core.utils

/**
 * Буквы башкирского алфавита, которых нет в русском.
 *
 * Буквы записаны кодами Unicode, а не символами: многие из них на вид
 * не отличить от латинских «двойников» (например, кириллическая «ә» U+04D9
 * и латинская «ə» U+0259), и по коду сразу видно, какой символ стоит в списке.
 */
object BashkirAlphabet {

    /** Строчные буквы в порядке башкирского алфавита. */
    val letters: List<Char> = listOf(
        'ғ', // ғ
        'ҙ', // ҙ
        'ҡ', // ҡ
        'ң', // ң
        'ө', // ө
        'ҫ', // ҫ
        'ү', // ү
        'һ', // һ
        'ә', // ә
    )

    /**
     * Есть ли в [text] хотя бы одна башкирская буква из [letters].
     * Регистр не важен: «Ә» превращается в «ә» и тоже находится.
     */
    fun containsBashkirLetter(text: String): Boolean =
        text.lowercase().any { it in letters }
}
